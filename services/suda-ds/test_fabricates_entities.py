    if call_a is None and not direct_a:
        ok(f"未复用被否掉的答复（direct 为空、guard={guard_a}）→ 落到兜底/可见失败"
           f"（重试 {always_text.n} 发，strict-trigger={reasons_a}）")
    else:
        bad(f"★ 判据命中后仍把编造答复当最终答案交付"
            f"（direct 长度 {len(direct_a)}，call={call_a}，strict-trigger={reasons_a}）")

    # ── [11] ★★★ 坑 32 路径 B：**兜底那一轮**也必须过 fabricate 判据 ──────
    #
    # 「判据命中 → 三发重试失败 → 兜底又编一份」这条链的**最后一环原先没有任何守卫**
    # （只查 `sanitize_answer` 与 `sounds_unfinished`，两者都拦不住点名清单）。
    # 取舍：宁可 **502 可见失败**，也不交付一份编造的导师清单。
    print("\n[11] ★★★ 坑 32-B：兜底那一轮的答复也必须过 fabricate 判据")
    seen_b: list[tuple[str, dict]] = []
    orig_b = {k: getattr(suda_api, k)
              for k in ("_trace_tool", "model_once", "answer_message_once", "TOOL_MODE")}
    try:
        suda_api._trace_tool = lambda stage, payload: seen_b.append((stage, payload))
        suda_api.model_once = lambda prompt, model, reset_once=None: FIELD_LIST  # 决策轮编造
        suda_api.answer_message_once = lambda converted, model, reset_once=None: {
            "text": FIELD_LIST, "name": ""}                                      # 兜底轮又编造
        suda_api.TOOL_MODE = True
        got_502 = None
        try:
            list(suda_api.chat_stream(CONTEXT, "m", TOOLS, None))
        except suda_api.UpstreamError as exc:
            got_502 = exc
    finally:
        for k, v in orig_b.items():
            setattr(suda_api, k, v)

    rejected = [p for s, p in seen_b if s == "fallback-rejected"]
    if got_502 is not None:
        ok(f"兜底轮又编造 → **可见失败**（{got_502}；trace 记了 {len(rejected)} 条 fallback-rejected）")
    else:
        bad("★ 兜底轮编造的清单被交付了 —— 这条链的最后一环没有守卫")

    print(f"\n结果：PASS={PASS}  FAIL={FAIL}")
    return 1 if FAIL else 0


